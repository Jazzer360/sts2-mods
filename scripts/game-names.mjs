// Writes mods/SpireQoL/Sim/GameNames.g.cs: a typed name (PowerId, RelicId, CardId) for every power, relic and card class the game has, on its
// beta branch and its main branch (decision #78), from the decompiled source (~/git/sts2-decompiled, ~/git/sts2-decompiled-main).
// Run it after scripts/decompile.ps1, with the coverage review. The simulator names powers and relics through these (PowerId.Thorns),
// and the catalog tests check them against the installed game. A name the game adds later still works without one (new PowerId("X")).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const home = os.homedir();
const branches = [
  { name: 'beta', root: path.join(home, 'git', 'sts2-decompiled') },
  { name: 'main', root: path.join(home, 'git', 'sts2-decompiled-main') },
];

/** The concrete classes in a game folder (e.g. Models.Powers), by file. */
function classes(root, kind) {
  const dirs = [path.join(root, `MegaCrit.Sts2.Core.Models.${kind}`), path.join(root, 'MegaCrit', 'sts2', 'Core', 'Models', kind)];
  const dir = dirs.find(d => fs.existsSync(d));
  if (!dir) throw new Error(`no ${kind} folder under ${root}`);
  const names = new Set();
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith('.cs')) continue;
    const text = fs.readFileSync(path.join(dir, f), 'utf8');
    const m = text.match(/public (sealed |)class (\w+)(?: : (\w+))?/);
    if (!m || /abstract class/.test(text) || m[2] !== f.slice(0, -3) || /^I[A-Z]/.test(m[3] ?? '')) continue; // not a model (VakuuCardSelector: an ICardSelector)
    names.add(m[2]);
  }
  return names;
}

function members(kind, type, strip) {
  const [beta, main] = branches.map(b => classes(b.root, kind));
  const all = [...new Set([...beta, ...main])].sort();
  const lines = [];
  for (const cls of all) {
    const member = strip && cls.endsWith(strip) && cls.length > strip.length ? cls.slice(0, -strip.length) : cls;
    const where = beta.has(cls) && main.has(cls) ? null : beta.has(cls) ? 'Beta branch only.' : 'Main branch only.';
    if (where) lines.push(`    /// <summary>${where}</summary>`);
    lines.push(`    public static readonly ${type} ${member} = new("${cls}");`);
  }
  const only = which => all.filter(c => which === 'beta' ? beta.has(c) && !main.has(c) : main.has(c) && !beta.has(c));
  return { lines, count: all.length, betaOnly: only('beta'), mainOnly: only('main') };
}

const powers = members('Powers', 'PowerId', 'Power');
const relics = members('Relics', 'RelicId', null);
const cards = members('Cards', 'CardId', null);
const out = `// <auto-generated>
// scripts/game-names.mjs, from the decompiled game (beta and main). Don't edit: run the script after scripts/decompile.ps1.
// </auto-generated>

namespace SpireQoL.Sim;

/// <summary>Every power class the game has (${powers.count}), named as the simulator names it.</summary>
public readonly partial record struct PowerId
{
${powers.lines.join('\n')}
}

/// <summary>Every relic class the game has (${relics.count}), named as the simulator names it.</summary>
public readonly partial record struct RelicId
{
${relics.lines.join('\n')}
}

/// <summary>
/// The classes only one of the game's branches has (decision #78). Code that works around one (reads it by name because the other
/// branch lacks it) is checked against these: once both branches have it, the workaround has to go (GameBranchTests).
/// </summary>
public static class GameBranches
{
    public static readonly IReadOnlySet<string> BetaOnly = new HashSet<string>
    {
${[...powers.betaOnly, ...relics.betaOnly, ...cards.betaOnly].map(c => `        "${c}",`).join('\n')}
    };

    public static readonly IReadOnlySet<string> MainOnly = new HashSet<string>
    {
${[...powers.mainOnly, ...relics.mainOnly, ...cards.mainOnly].map(c => `        "${c}",`).join('\n')}
    };
}

/// <summary>Every card class the game has (${cards.count}), named as the simulator names it.</summary>
public readonly partial record struct CardId
{
${cards.lines.join('\n')}
}
`;
const target = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..', 'mods', 'SpireQoL', 'Sim', 'GameNames.g.cs');
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(process.cwd(), target)}: ${powers.count} powers, ${relics.count} relics, ${cards.count} cards`);
