// Generates mods/SpireQoL/Diagnostics/CoverageLedger.Data.cs from the decompiled game source:
//  - every game model class (relics, powers, cards, monsters, orbs, potions, enchantments,
//    afflictions) with the combat hooks it overrides (Diagnostics/CoverageHooks.txt). Each needs a
//    reviewed entry in CoverageLedger.cs (covered, ignore or gap, written from its hook bodies);
//  - every relic that can affect a fight (any hook outside Diagnostics/OutOfCombatHooks.txt). Each
//    needs a tab, a tracker row or a reviewed reason in RelicTracking.cs.
// It lists what's missing a review. The mod compares the data with the game it's running on and
// reports new, changed and unreviewed classes when they show up.
//
// Usage: node scripts/coverage-ledger.mjs   (after scripts/decompile.ps1 for a new game version)
import fs from "node:fs";
import path from "node:path";
import os from "node:os";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const diag = path.join(root, "mods", "SpireQoL", "Diagnostics");
const decomp = path.join(os.homedir(), "git", "sts2-decompiled");
// A namespace folder: one folder per namespace (MegaCrit.Sts2.Core.Models.Cards, from v0.113.0) or
// nested folders (MegaCrit/sts2/Core/Models/Cards, before).
const modelsDir = sub => {
  const flat = path.join(decomp, ["MegaCrit.Sts2.Core.Models", sub].filter(Boolean).join("."));
  return fs.existsSync(flat) ? flat : path.join(decomp, "MegaCrit", "sts2", "Core", "Models", sub);
};
const version = JSON.parse(fs.readFileSync(path.join(decomp, "VERSION.json"), "utf8").replace(/^﻿/, "")).version;
const lines = file => fs.readFileSync(file, "utf8").split(/\r?\n/).map(l => l.trim()).filter(l => l && !l.startsWith("#"));

// Hooks that can change what happens in a fight and aren't already covered by the game's own math
// that the mod calls (Hook.ModifyDamage, ModifyBlock, ModifyCardPlayCount, ModifyXValue,
// ModifyOrbPassiveTriggerCounts, ShouldEtherealTrigger).
const hooks = lines(path.join(diag, "CoverageHooks.txt"));
const folders = ["Relics", "Powers", "Cards", "Monsters", "Orbs", "Potions", "Enchantments", "Afflictions"];

const rows = [];
// An enchantment's or affliction's OnPlay acts on every play of its card, after the card (CardModel: EnchantmentModel.OnPlay):
// reviewed like a hook. A card's own OnPlay is what PlayFacts reads, so it isn't one. Kept in step with CoverageLedger.OnCardHooks.
const onCardHooks = { Enchantments: ["OnPlay"], Afflictions: ["OnPlay"] };
const hookRe = new RegExp(`public override [^(=]*\\b(${hooks.join("|")})\\(`, "g");
const combatHooksOf = (src, folder) => {
  const onCard = (onCardHooks[folder] || []).filter(h => new RegExp("public override [^(=]*\\b" + h + "\\(").test(src));
  return [...new Set([...src.matchAll(hookRe)].map(m => m[1]).concat(onCard))].sort();
};
for (const folder of folders) {
  const dir = modelsDir(folder);
  if (!fs.existsSync(dir)) continue;
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith(".cs")) continue;
    const found = combatHooksOf(fs.readFileSync(path.join(dir, f), "utf8"), folder);
    if (found.length) rows.push({ folder, type: f.slice(0, -3), hooks: found });
  }
}

// Main's combat hooks for the ledger's classes whose hooks differ there (decision #163: one DLL serves both branches), so a main player's game
// doesn't report a reviewed class as changed. Each is reviewed for main too: the script lists them.
const decompMain = path.join(os.homedir(), "git", "sts2-decompiled-main");
const mainRows = [];
if (fs.existsSync(decompMain)) {
  for (const r of rows) {
    const file = path.join(decompMain, "MegaCrit.Sts2.Core.Models." + r.folder, r.type + ".cs");
    if (!fs.existsSync(file)) continue;
    const found = combatHooksOf(fs.readFileSync(file, "utf8"), r.folder);
    if (found.join(",") !== r.hooks.join(",")) mainRows.push({ folder: r.folder, type: r.type, hooks: found });
  }
}

// Relics that affect fights: every hook they override except the out-of-combat ones.
const allHooks = new Set([...fs.readFileSync(path.join(modelsDir(""), "AbstractModel.cs"), "utf8").matchAll(/public virtual [^(]*?\b(\w+)\(/g)].map(m => m[1]));
const outOfCombat = new Set(lines(path.join(diag, "OutOfCombatHooks.txt")));
const relicRows = [];
for (const f of fs.readdirSync(modelsDir("Relics"))) {
  if (!f.endsWith(".cs")) continue;
  const src = fs.readFileSync(path.join(modelsDir("Relics"), f), "utf8");
  const ov = [...new Set([...src.matchAll(/public override [^(=]*?\b(\w+)\(/g)].map(m => m[1]))]
    .filter(h => (allHooks.has(h) || h.startsWith("TryModify")) && !outOfCombat.has(h)).sort();
  if (ov.length) relicRows.push({ type: f.slice(0, -3), hooks: ov });
}

const out = [];
out.push("// <auto-generated> by scripts/coverage-ledger.mjs from the decompiled game " + version + ". Don't edit; rerun the script.");
out.push("namespace SpireQoL.Diagnostics;");
out.push("");
out.push("internal static partial class CoverageLedger");
out.push("{");
out.push(`    public const string LedgerGameVersion = "${version}";`);
out.push("");
out.push("    /// <summary>The hooks that need a rule or a reviewed reason (from Diagnostics/CoverageHooks.txt).</summary>");
out.push("    private static readonly string[] Hooks = { " + hooks.map(h => `"${h}"`).join(", ") + " };");
out.push("");
out.push("    /// <summary>Game classes with combat hooks: folder, class, hooks it overrides.</summary>");
out.push("    private static readonly (string Folder, string Type, string Hooks)[] Generated =");
out.push("    {");
for (const r of rows) out.push(`        ("${r.folder}", "${r.type}", "${r.hooks.join(",")}"),`);
out.push("    };");
out.push("");
out.push("    /// <summary>Main's combat hooks for the classes whose hooks differ there (one DLL serves both branches: decision #163): the coverage check takes either set.</summary>");
out.push("    private static readonly (string Folder, string Type, string Hooks)[] GeneratedMain =");
out.push("    {");
for (const r of mainRows) out.push(`        ("${r.folder}", "${r.type}", "${r.hooks.join(",")}"),`);
out.push("    };");
out.push("");
out.push("    /// <summary>Relics that can affect a fight (any hook outside Diagnostics/OutOfCombatHooks.txt), with those hooks: each needs a tab, a tracker row or a reviewed reason (RelicTracking).</summary>");
out.push("    public static readonly (string Type, string Hooks)[] RelicFightHooks =");
out.push("    {");
for (const r of relicRows) out.push(`        ("${r.type}", "${r.hooks.join(",")}"),`);
out.push("    };");
out.push("");
out.push("    /// <summary>Hooks that only act outside fights (Diagnostics/OutOfCombatHooks.txt): a relic overriding only these doesn't affect fights.</summary>");
out.push("    public static readonly string[] OutOfCombatHooks = { " + [...outOfCombat].map(h => `"${h}"`).join(", ") + " };");
out.push("");
out.push("    /// <summary>Hooks through which a relic changes a choice outside combat (Diagnostics/ChoiceHooks.txt): each such relic needs a reminder rule or a reviewed reason (RelicChoiceTracking).</summary>");
out.push("    public static readonly string[] ChoiceHooks = { " + lines(path.join(diag, "ChoiceHooks.txt")).map(h => `"${h}"`).join(", ") + " };");
out.push("}");
fs.writeFileSync(path.join(diag, "CoverageLedger.Data.cs"), out.join("\n") + "\n");

const keys = file => new Set([...fs.readFileSync(file, "utf8").matchAll(/^\s*\["(\w+)"\] = "/gm)].map(m => m[1]));
const reviewed = keys(path.join(diag, "CoverageLedger.cs"));
const missing = rows.filter(r => !reviewed.has(r.type)).map(r => r.type);
const stale = [...reviewed].filter(t => !rows.some(r => r.type === t));
console.log(`game ${version}: ${rows.length} classes with combat hooks; ${reviewed.size} reviewed entries`);
console.log(missing.length ? `no reviewed entry (review their hooks, add to CoverageLedger.Reviewed): ${missing.join(", ")}` : "every class has a reviewed entry");
if (stale.length) console.log(`entries for classes without combat hooks now (remove): ${stale.join(", ")}`);
if (mainRows.length) console.log(`combat hooks that differ on main (review each entry for main's bodies too):\n${mainRows.map(r => `  ${r.type}: beta ${rows.find(b => b.type === r.type && b.folder === r.folder).hooks.join(",")} | main ${r.hooks.join(",") || "none"}`).join("\n")}`);

const catalog = fs.readFileSync(path.join(root, "mods", "SpireQoL", "Menu", "SettingsCatalog.cs"), "utf8");
const specs = fs.readFileSync(path.join(root, "mods", "SpireQoL", "Data", "RelicSpecs.cs"), "utf8");
// Reminder-only rows (no tab, no tracker) don't count as shown in fights.
const fightCatalog = catalog.split(/\r?\n/).filter(l => !l.includes(", null, Reminder:")).join("\n");
const shown = new Set([...(fightCatalog + specs).matchAll(/nameof\((\w+)\)|new\("(\w+)"/g)].map(m => m[1] || m[2]));
const reasons = keys(path.join(diag, "RelicTracking.cs"));
const untracked = relicRows.filter(r => !shown.has(r.type) && !reasons.has(r.type));
console.log(`${relicRows.length} relics affect fights; ${relicRows.filter(r => shown.has(r.type)).length} have a tab or tracker row, ${reasons.size} a reviewed reason`);
console.log(untracked.length ? `relics with no tab, tracker row or reason (review, add to RelicTracking.Reasons):\n${untracked.map(r => `  ${r.type}: ${r.hooks.join(",")}`).join("\n")}` : "every relic that affects fights is tracked or reviewed");

// ---------------------------------------------------------------- goal 3 and docs/RELICS.md
// Relics that change a choice outside combat (a hook in Diagnostics/ChoiceHooks.txt): each needs a
// Run Reminders rule (Data/ChoiceReminders.cs) or a reviewed reason (RelicChoiceTracking.cs).
const choiceHooks = new Set(lines(path.join(diag, "ChoiceHooks.txt")));
const strRe = String.raw`"((?:[^"\\]|\\.)*)"`;
const unq = s => s == null ? null : s.replace(/\\"/g, '"');
const dict = file => new Map([...fs.readFileSync(file, "utf8").matchAll(new RegExp(String.raw`^\s*\["(\w+)"\] = ${strRe}`, "gm"))].map(m => [m[1], unq(m[2])]));
const fightReasons = dict(path.join(diag, "RelicTracking.cs"));
const choiceReasons = dict(path.join(diag, "RelicChoiceTracking.cs"));
// The relics with a rule: read from their own code (Data/RelicReadings, decision #359) and the map rules, as the catalog tests' snapshot holds them.
const reminderRules = new Set(fs.readFileSync(path.join(root, "tests", "SpireQoL.Catalog.Tests", "Snapshots", "reminder-rules.txt"), "utf8")
  .split(/\r?\n/).filter(line => /\| shows at \w/.test(line)).map(line => line.split(":")[0]));

// Settings catalog rows for relics: tab (crossed ones are `Crossed + "..."`), tracker and reminder text.
const rowsByRelic = new Map();
for (const m of catalog.matchAll(new RegExp(String.raw`new\((?:nameof\((\w+)\)|"(\w+)"), SourceGroup\.Relic, (?:Tag: )?(?:null|(Crossed \+ )?${strRe})(?:, (?:null|${strRe}))?([^\n]*)`, "g"))) {
  // The row's text up to the next row (a row can span lines), with its text for each place a reminder shows.
  const end = catalog.indexOf("\n        new(", m.index + 1);
  const rest = catalog.slice(m.index, end < 0 ? undefined : end);
  const placeName = { Reward: "card rewards", Event: "events", Shop: "shops", Map: "map" };
  const places = [...rest.matchAll(new RegExp(String.raw`\b(Reward|Event|Shop|Map): ${strRe}`, "g"))].map(x => `${placeName[x[1]]}: ${unq(x[2])}`);
  rowsByRelic.set(m[1] || m[2], {
    tag: m[4] == null ? null : (m[3] ? "crossed: " : "") + unq(m[4]), tracker: unq(m[5]),
    doublePlay: rest.includes('TagPrefix: "double-play:"'),
    reminder: places.length ? places.join("; ") : null,
  });
}

const relicDir = modelsDir("Relics");
const allRelics = [];
for (const f of fs.readdirSync(relicDir).filter(f => f.endsWith(".cs")).sort()) {
  const src = fs.readFileSync(path.join(relicDir, f), "utf8");
  if (!/class \w+ : \w*RelicModel\b/.test(src) && !/override RelicRarity Rarity/.test(src)) continue;
  if (/\babstract class\b/.test(src)) continue;
  const type = f.slice(0, -3);
  const rarity = (src.match(/RelicRarity Rarity => RelicRarity\.(\w+)/) || [])[1] || "?";
  const ov = [...new Set([...src.matchAll(/public override [^(=]*?\b(\w+)\(/g)].map(m => m[1]))];
  allRelics.push({ type, rarity, choice: ov.filter(h => choiceHooks.has(h)).sort(), fight: (relicRows.find(r => r.type === type) || {}).hooks || [] });
}
const unreviewedChoice = allRelics.filter(r => r.choice.length && !reminderRules.has(r.type) && !choiceReasons.has(r.type));
console.log(`${allRelics.filter(r => r.choice.length).length} relics change choices outside combat; ${reminderRules.size} have a reminder, ${choiceReasons.size} a reviewed reason`);
console.log(unreviewedChoice.length ? `relics with no reminder or reason (review, add to RelicChoiceTracking.Reasons):\n${unreviewedChoice.map(r => `  ${r.type}: ${r.choice.join(",")}`).join("\n")}` : "every relic that changes a choice outside combat is covered or reviewed");

const esc = s => s.replace(/\|/g, "\\|");
const reason = r => r.startsWith("gap:") ? `**Gap:** ${r.slice(4).trim()}` : r.startsWith("none:") ? `Nothing shown: ${r.slice(5).trim()}` : r;
const display = t => t.replace(/([a-z])([A-Z])/g, "$1 $2").replace(/([A-Z])([A-Z][a-z])/g, "$1 $2").replace(/ (Of|The|And|To|A) /g, (_, w) => ` ${w.toLowerCase()} `);
const md = [];
md.push("# Relics");
md.push("");
md.push(`Every relic in the game (${version}) and what Spire QoL does for it. Generated by \`scripts/coverage-ledger.mjs\` from the decompiled game, the settings catalog (\`Menu/SettingsCatalog.cs\`), the reminder rules (\`Data/ChoiceReminders.cs\`) and the reviewed reasons (\`Diagnostics/RelicTracking.cs\`, \`Diagnostics/RelicChoiceTracking.cs\`); don't edit it, rerun the script.`);
md.push("");
md.push("- **In fights:** the on-card tab it gets (crossed = a red slash), its Relic Counters row, or why nothing is shown. A dash: it has no hook that acts in a fight.");
md.push("- **Outside fights:** its Run Reminders icon or card-reward row, or why nothing is shown. A dash: it changes no choice outside fights (pickup-only effects, run counters).");
md.push("- **Gap** marks something worth showing that isn't yet; **unreviewed** marks a relic whose hooks haven't been reviewed (a new game version).");
md.push("");
const counts = { fight: 0, fightGap: 0, choice: 0, choiceGap: 0 };
md.push("| Relic | Rarity | In fights | Outside fights |");
md.push("|---|---|---|---|");
for (const r of allRelics.sort((a, b) => display(a.type).localeCompare(display(b.type)))) {
  const row = rowsByRelic.get(r.type);
  const fight = [];
  if (row?.tag) fight.push(row.tag.startsWith("crossed: ") ? `Crossed tab: ${row.tag.slice(9)}` : `${row.doublePlay ? "Double-play tab" : "Tab"}: ${row.tag}`);
  if (row?.tracker) fight.push(`Tracker: ${row.tracker}`);
  if (!fight.length && r.fight.length) fight.push(fightReasons.has(r.type) ? reason(fightReasons.get(r.type)) : "**unreviewed**");
  if (fight.length) counts.fight++;
  if (fight.some(x => x.startsWith("**"))) counts.fightGap++;
  const out = [];
  if (row?.reminder) out.push(`Reminder: ${row.reminder.replace(/^Crossed\. /, "crossed. ")}`);
  if (choiceReasons.has(r.type) && !(row?.reminder && choiceReasons.get(r.type).startsWith("none:"))) out.push(reason(choiceReasons.get(r.type)));
  if (!out.length && r.choice.length) out.push("**unreviewed**");
  if (out.length) counts.choice++;
  if (out.some(x => x.startsWith("**"))) counts.choiceGap++;
  md.push(`| ${display(r.type)} | ${r.rarity} | ${esc(fight.join("; ") || "—")} | ${esc(out.join("; ") || "—")} |`);
}
md.splice(md.indexOf("| Relic | Rarity | In fights | Outside fights |"), 0,
  `${allRelics.length} relics: ${counts.fight} matter in fights (${counts.fightGap} with a gap or unreviewed), ${counts.choice} change a choice outside fights (${counts.choiceGap} with a gap or unreviewed).`, "");
fs.writeFileSync(path.join(root, "docs", "RELICS.md"), md.join("\n") + "\n");
console.log(`wrote docs/RELICS.md (${allRelics.length} relics)`);

// ---------------------------------------------------------------- docs/TRACKER.md known gaps
// The open gaps of all three review files, between the markers in TRACKER.md, so the list never drifts from them.
const trackerPath = path.join(root, "docs", "TRACKER.md");
const tracker = fs.readFileSync(trackerPath, "utf8");
const nl = tracker.includes("\r\n") ? "\r\n" : "\n";
const gapsOf = (file, label) => [...dict(path.join(diag, file))].filter(([, r]) => r.startsWith("gap:"))
  .sort(([a], [b]) => a.localeCompare(b)).map(([k, r]) => `  - [ ] ${k} (${label}): ${r.slice(4).trim()}`);
const gapLines = [...gapsOf("CoverageLedger.cs", "ledger"), ...gapsOf("RelicTracking.cs", "relic tracking"), ...gapsOf("RelicChoiceTracking.cs", "outside fights"),
  ...gapsOf("ModelEffectCheck.cs", "model's effect")];
const block = ["<!-- gaps:start (written by scripts/coverage-ledger.mjs from the review files; don't edit by hand) -->",
  `- Known gaps (${gapLines.length}; each is logged when present in a fight):`, ...gapLines, "<!-- gaps:end -->"].join(nl);
const marked = /<!-- gaps:start[^\n]*-->[\s\S]*?<!-- gaps:end -->/;
if (marked.test(tracker)) {
  fs.writeFileSync(trackerPath, tracker.replace(marked, block));
  console.log(`wrote docs/TRACKER.md known gaps (${gapLines.length})`);
} else console.log("docs/TRACKER.md has no gaps markers: known gaps not written");
