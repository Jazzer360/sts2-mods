// The decisions: their full text in docs/decisions/<range>.md (one file per hundred, numbers never change), and docs/DECISIONS.md, the index
// generated from them: one line per decision, its title, its status, a link to its text, and the later decisions whose "Replaced" line names
// it (so a decision another one took over in part or whole says so, even where its own status wasn't updated).
//
// Usage:
//   node scripts/decisions.mjs            regenerate docs/DECISIONS.md from docs/decisions/*.md
//   node scripts/decisions.mjs --check    exit 1 if docs/DECISIONS.md isn't what it would generate (the decisions tests run this check too)
//   node scripts/decisions.mjs --split    one-time: move the full text out of a docs/DECISIONS.md that still holds it, then regenerate
//
// A new decision: append it, in full, to the newest range file (### N. Title — active (date), its text, *Why:*, *Replaced:*), then run this.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const indexPath = path.join(root, "docs", "DECISIONS.md");
const folder = path.join(root, "docs", "decisions");
const heading = /^### (\d+)\. (.*?) — (.+?)\s*$/;

const rangeOf = n => { const start = Math.floor(n / 100) * 100; const from = Math.max(start, 1); return `${String(from).padStart(3, "0")}-${String(start + 99).padStart(3, "0")}`; };

const intro = `# Decisions

Design and engineering decisions for these mods, newest last. Each says what was decided, why, and what it replaced. **A decision stays until there's a good reason to change it**: changing one means adding a new entry that names the old one and the reason, not quietly drifting back. Going back to an earlier path needs a reason the earlier entry didn't already weigh.

Status: **active**, **superseded by #N**, **revised by #N** (partly replaced: the replaced part is struck through), or **in progress**. A superseded decision's title is struck through and its text kept, for the history. *Later:* the decisions whose *Replaced* line names this one (in part or whole): read them before relying on it.

This file is the index, generated by \`node scripts/decisions.mjs\` from the full text in [docs/decisions/](decisions/) (one file per hundred; a decision's number never changes, and the code cites them by number). To add one: append it in full to the newest file there (\`### N. Title — active (date)\`, its text, \`*Why:*\`, \`*Replaced:*\`), then run the script. To read one: follow its link, or search the folder for \`### N.\`.

---
`;

function blocks(text) {
  // Each decision: its heading line and every line up to the next decision's heading.
  const lines = text.split(/\r?\n/);
  const found = [];
  let current = null;
  for (const line of lines) {
    const match = heading.exec(line);
    if (match) {
      current = { number: Number(match[1]), title: match[2], status: match[3], lines: [line] };
      found.push(current);
    } else if (current) current.lines.push(line);
  }
  for (const block of found) while (block.lines.length && /^(\s*|---)$/.test(block.lines[block.lines.length - 1])) block.lines.pop();
  return found;
}

function readAll() {
  const files = fs.existsSync(folder) ? fs.readdirSync(folder).filter(name => /^\d{3}-\d{3}\.md$/.test(name)).sort() : [];
  return files.flatMap(name => blocks(fs.readFileSync(path.join(folder, name), "utf8")).map(block => ({ ...block, file: name })));
}

function index(all) {
  // Later decisions naming this one in their Replaced line.
  const later = new Map();
  for (const block of all) {
    for (const line of block.lines.filter(line => line.startsWith("*Replaced:*")))
      for (const match of line.matchAll(/(?:decisions? |#)(\d+)(?:(?:, | and | or )#?(\d+))*/g))
        for (const number of match[0].match(/\d+/g).map(Number))
          if (number !== block.number && number < block.number) {
            if (!later.has(number)) later.set(number, new Set());
            later.get(number).add(block.number);
          }
  }
  const out = [intro];
  let range = "";
  for (const block of all) {
    if (block.file !== range) {
      range = block.file;
      out.push(`\n## [${range.replace(".md", "").replace("-", "–")}](decisions/${range})\n`);
    }
    const after = later.get(block.number);
    const laterText = after && after.size ? ` · *Later:* ${[...after].sort((a, b) => a - b).map(n => `[#${n}](decisions/${rangeOf(n)}.md#d${n})`).join(", ")}` : "";
    out.push(`- [#${block.number}](decisions/${block.file}#d${block.number}) ${block.title} — ${block.status}${laterText}`);
  }
  return out.join("\n") + "\n";
}

function write(file, text) { fs.writeFileSync(file, text.replace(/\r?\n/g, "\n")); }

const mode = process.argv[2];
if (mode === "--split") {
  const whole = blocks(fs.readFileSync(indexPath, "utf8"));
  if (whole.length === 0 || !whole[0].lines.some(line => line.startsWith("*Why:*") || line.length > 200)) throw new Error("docs/DECISIONS.md holds no decision text to split");
  fs.mkdirSync(folder, { recursive: true });
  const byRange = new Map();
  for (const block of whole) {
    const range = rangeOf(block.number);
    if (!byRange.has(range)) byRange.set(range, []);
    byRange.get(range).push(block);
  }
  for (const [range, list] of byRange) {
    const [from, to] = range.split("-").map(Number);
    const text = [`# Decisions ${from}–${to}`, "", `The full text of decisions ${from} to ${to}, newest last. The index, with each one's status and the later decisions that replaced it in part or whole, is [docs/DECISIONS.md](../DECISIONS.md).`, ""];
    for (const block of list) text.push(`<a id="d${block.number}"></a>`, ...block.lines, "");
    write(path.join(folder, `${range}.md`), text.join("\n"));
  }
  console.log(`split ${whole.length} decisions into ${byRange.size} files`);
}
const all = readAll();
const generated = index(all);
if (mode === "--check") {
  const now = fs.readFileSync(indexPath, "utf8").replace(/\r\n/g, "\n");
  if (now !== generated) { console.error("docs/DECISIONS.md isn't the index of docs/decisions/: run node scripts/decisions.mjs"); process.exit(1); }
  console.log(`docs/DECISIONS.md is the index of ${all.length} decisions`);
} else {
  write(indexPath, generated);
  console.log(`wrote docs/DECISIONS.md: ${all.length} decisions`);
}
